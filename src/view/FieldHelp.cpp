#include "view/FieldHelp.h"

namespace lab2 {

const char* columnHelp(int column) {
    switch (column) {
        case 0:
            return "Имя файла вместе с папкой. Имя определяется по сигнатуре файла, а не по расширению.";
        case 1:
            return "Формат, определённый по сигнатуре первых байт: BMP, PNG, JPEG, GIF, TIFF или PCX.";
        case 2:
            return "Размер изображения в пикселях, взятый из заголовка файла.";
        case 3:
            return "Разрешение в точках на дюйм. Значение считается из поля заголовка, где это возможно; "
                   "если поле равно нулю, показывается «не задано».";
        case 4:
            return "Число бит на один пиксель (сумма по всем каналам цвета).";
        case 5:
            return "Алгоритм сжатия, записанный в файле: без сжатия, RLE, LZW, DEFLATE и другие.";
        case 6:
            return "Результат проверки целостности: «ОК», «Предупреждение», «Повреждён» или «Не изображение».";
        case 7:
            return "Число различных цветов, найденное при декодировании пикселей.";
        default:
            return "";
    }
}

std::string statusHelp() {
    return "Статус «ОК» означает, что сигнатура и заголовки согласованы, а обязательные поля заполнены. "
           "«Предупреждение» - файл читается, но есть несоответствия (например, расширение не совпадает "
           "с форматом). «Повреждён» - структура файла нарушена. «Не изображение» - сигнатура не найдена.";
}

}